import { kebab, pluralize } from '../definition/shared.js'
import type { IndexGenerator } from '@adonisjs/assembler/index_generator'
import type { FileBuffer, VirtualFileSystem } from '@adonisjs/assembler'

interface IndexAdminOptions {
  source?: string
  output?: string
}

function resourceKey(filePath: string) {
  const filename = filePath
    .split('/')
    .pop()!
    .replace(/\.(?:[cm]?[jt]sx?)$/, '')
  return pluralize(kebab(filename.replace(/_resource$/i, '')))
}

function panelKey(filePath: string) {
  const filename = filePath
    .split('/')
    .pop()!
    .replace(/\.(?:[cm]?[jt]sx?)$/, '')
  return filename
}

function writeRegistry(
  name: string,
  files: Record<string, string>,
  buffer: FileBuffer,
  keyFor: (path: string) => string
) {
  buffer.writeLine(`export const ${name} = {`).indent()
  for (const key of Object.keys(files).sort()) {
    buffer.writeLine(`${JSON.stringify(keyFor(key))}: () => import('${files[key]}'),`)
  }
  buffer.dedent().writeLine('} as const')
}

function renderAdminIndex(
  vfs: VirtualFileSystem,
  buffer: FileBuffer,
  helpers: { toImportPath(filePath: string): string }
) {
  const discovered = vfs.asList()
  const resources: Record<string, string> = {}
  const panels: Record<string, string> = {}
  for (const key of Object.keys(discovered).sort()) {
    const filePath = discovered[key]
    const importPath = helpers.toImportPath(filePath)
    if (key.startsWith('resources/')) resources[key.slice('resources/'.length)] = importPath
    if (key.startsWith('panels/')) panels[key.slice('panels/'.length)] = importPath
  }
  buffer.writeLine('// generated by @rikology/pupitre')
  writeRegistry('resources', resources, buffer, resourceKey)
  buffer.writeLine('')
  writeRegistry('panels', panels, buffer, panelKey)
}

/**
 * Indexes Pupitre resources and panels for use by host applications.
 * The assembler's IndexGenerator handles both initial build generation and
 * add/remove watcher events in `serve`.
 */
export function indexAdmin(options: IndexAdminOptions = {}) {
  return {
    run(_: unknown, __: unknown, indexGenerator: IndexGenerator) {
      indexGenerator.add('pupitreAdmin', {
        source: options.source ?? 'app/admin',
        glob: ['**/*.{ts,tsx,js,jsx,mts,cts,mjs,cjs}'],
        output: options.output ?? '.adonisjs/server/admin.ts',
        importAlias: '#admin',
        filter(filePath, isDirectory) {
          if (isDirectory) return true
          const relativePath = filePath.replaceAll('\\', '/')
          if (relativePath.includes('/resources/'))
            return /_resource\.(?:[cm]?[jt]sx?)$/.test(relativePath)
          return relativePath.includes('/panels/')
        },
        as(vfs, buffer, _config, helpers) {
          renderAdminIndex(vfs, buffer, helpers)
        },
      })
    },
  }
}
