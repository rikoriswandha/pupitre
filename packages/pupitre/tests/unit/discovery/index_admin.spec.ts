import { test } from '@japa/runner'
import type { IndexGenerator } from '@adonisjs/assembler/index_generator'
import type { FileBuffer, VirtualFileSystem } from '@adonisjs/assembler'
import { indexAdmin } from '../../../src/discovery/index_admin.js'

test.group('indexAdmin', () => {
  test('generates deterministic resource and panel registries', async ({ assert }) => {
    const files = {
      'panels/admin.ts': '/app/admin/panels/admin.ts',
      'resources/user_resource.ts': '/app/admin/resources/user_resource.ts',
      'resources/post_resource.ts': '/app/admin/resources/post_resource.ts',
      'resources/category_resource.ts': '/app/admin/resources/category_resource.ts',
      'resources/APIKey_resource.ts': '/app/admin/resources/APIKey_resource.ts',
      'pages/settings_page.ts': '/app/admin/pages/settings_page.ts',
    }
    const generate = () => {
      const sources = new Map<string, Parameters<IndexGenerator['add']>[1]>()
      const generator = {
        add(name: string, config: Parameters<IndexGenerator['add']>[1]) {
          sources.set(name, config)
          return generator
        },
      } as unknown as IndexGenerator
      indexAdmin().run(undefined, undefined, generator)
      let output = ''
      let indentation = 0
      const buffer = {
        writeLine(line = '') {
          output += `${'  '.repeat(indentation)}${line}\n`
          return this
        },
        write(line: string) {
          output += line
          return this
        },
        indent() {
          indentation++
          return this
        },
        dedent() {
          indentation--
          return this
        },
      } as unknown as FileBuffer
      const config = sources.get('pupitreAdmin')!
      if (typeof config.as !== 'function') throw new Error('Expected custom index renderer')
      config.as({ asList: () => files } as unknown as VirtualFileSystem, buffer, config, {
        toImportPath: (filePath: string) =>
          filePath.replace('/app/admin/', '#admin/').replace(/\.ts$/, ''),
      })
      return output
    }

    const first = generate()
    assert.equal(first, generate())
    assert.snapshot(first).match()
    assert.equal(
      first,
      `// generated by @rikology/pupitre
export const resources = {
  "api-keys": () => import('#admin/resources/APIKey_resource'),
  "categories": () => import('#admin/resources/category_resource'),
  "posts": () => import('#admin/resources/post_resource'),
  "users": () => import('#admin/resources/user_resource'),
} as const

export const pages = {
  "settings": () => import('#admin/pages/settings_page'),
} as const

export const panels = {
  "admin": () => import('#admin/panels/admin'),
} as const
`
    )
  })
})
