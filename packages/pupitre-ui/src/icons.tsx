export function Icon({ name, ...props }: SVGProps<SVGSVGElement> & { name?: string }) {
  const IconComponent = name ? iconMap[name] : undefined
  if (!IconComponent) return null
  return <IconComponent aria-hidden="true" {...props} />
}
